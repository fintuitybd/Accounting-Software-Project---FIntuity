/**
 * Small functional icons for the public/auth-adjacent marketing surface.
 *
 * The marketing entry must not pull the full Lucide library into the first paint. These icons are
 * stroke paths on `currentColor`, always paired with visible text, and hidden from the accessibility
 * tree because the adjacent label carries the meaning.
 */
import type { ReactNode, SVGProps } from 'react';

type IconProps = Pick<SVGProps<SVGSVGElement>, 'className'> & {
  size?: number;
  'aria-hidden'?: boolean | 'true' | 'false';
};

function Icon({
  size = 16,
  className,
  children,
  ...rest
}: IconProps & { children: ReactNode }) {
  return (
    <svg
      width={size}
      height={size}
      viewBox="0 0 24 24"
      fill="none"
      stroke="currentColor"
      strokeWidth={2}
      strokeLinecap="round"
      strokeLinejoin="round"
      className={className}
      aria-hidden={rest['aria-hidden'] ?? 'true'}
      focusable="false"
    >
      {children}
    </svg>
  );
}

